/** Flatten all leaf services (those without subServices) from the entire catalog. */
export function flattenAllServices(): ServiceItem[] {
  const result: ServiceItem[] = [];
  for (const cat of SERVICE_CATEGORIES) {
    for (const svc of cat.services) {
      if (svc.subServices) {
        result.push(...svc.subServices);
      } else {
        result.push(svc);
      }
    }
  }
  return result;
}

/** Find service by id — traverses sub-services. Returns undefined if not found. */
export function findServiceById(id: string): ServiceItem | undefined {
  for (const cat of SERVICE_CATEGORIES) {
    for (const svc of cat.services) {
      if (svc.id === id) return svc;
      if (svc.subServices) {
        const found = svc.subServices.find((s) => s.id === id);
        if (found) return found;
      }
    }
  }
  return undefined;
}

/** Get the display name for a service id. */
export function getServiceName(id: string): string {
  return findServiceById(id)?.name ?? id;
}

/**
 * Find the parent subgroup id for a leaf service SKU/id, if it lives inside a
 * subServices group (e.g. "10096" → "radiation_shielding"). Returns null for
 * top-level leaf services that aren't nested in a group.
 */
export function getSubgroupIdForSku(skuOrId: string): string | null {
  for (const cat of SERVICE_CATEGORIES) {
    for (const svc of cat.services) {
      if (svc.subServices?.some((s) => s.id === skuOrId || s.sku === skuOrId)) {
        return svc.id;
      }
    }
  }
  return null;
}

/** Get the category name by category id. */
export function getCategoryName(id: string): string {
  return SERVICE_CATEGORIES.find((c) => c.id === id)?.name ?? id;
}

/** Format price as Israeli currency string, e.g. "₪1,200". */
export function formatPrice(price: number): string {
  if (price === 0) return 'כלול';
  return `₪${price.toLocaleString('he-IL')}`;
}
