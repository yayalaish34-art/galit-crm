//
// שתי ההודעות האלה נשלחות ללקוח דרך הבוט, אבל הנוסח נבנה *כאן* ונשלח לבוט
// כטקסט מוכן. זו הסיבה שכפתור "הצג הודעה מנוסחת" בממשק יכול להבטיח שמה
// שהעובד רואה הוא בדיוק מה שהלקוח יקבל — אילו הבוט היה מנסח מחדש בזמן
// השליחה, התצוגה המקדימה הייתה ניחוש.
// ─────────────────────────────────────────────────────────────

export type RadonKitMessageContext = {
  customerName?: string | null;
  siteAddress?: string | null;
  /** מספר הימים של תקופת הבדיקה (ברירת מחדל 90). */
  testDurationDays?: number | null;
  officePhone?: string | null;
};

const DEFAULT_KIT_DAYS = 90;

/**
 * הודעה 1 — נשלחת ברגע שהעובד מסמן "הערכה נשלחה ללקוח".
 *
 * שתי מטרות, ובסדר הזה: להסביר איך מציבים, ולבקש *תאריך התקנה*. הבקשה לתאריך
 * היא מה שמניע את כל השאר — בלי תשובה מהלקוח אין לנו נקודת התחלה, ולכן אין
 * ספירה לאחור ואין תזכורת החזרה. לכן היא מנוסחת כשאלה מפורשת בסוף ההודעה,
 * ולא כהערת אגב באמצע.
 */
export function buildKitInstructionsText(c: RadonKitMessageContext): string {
  const days = c.testDurationDays && c.testDurationDays > 0 ? c.testDurationDays : DEFAULT_KIT_DAYS;
  const where = c.siteAddress?.trim() ? ` (${c.siteAddress.trim()})` : '';
  const lines = [
    c.customerName?.trim() ? `שלום ${c.customerName.trim()},` : 'שלום,',
    '',
    `כאן גלית — החברה לאיכות הסביבה. ערכת בדיקת הראדון${where} יצאה אליך.`,
    '',
    // שלושת החוקים כלשונם בעלון שמצורף לערכה. שמירה על אותו נוסח בדיוק היא
    // מכוונת: לקוח שקורא בוואטסאפ משהו אחר ממה שכתוב בעלון שבידיו לא יודע
    // באיזה מהם לבטוח, ובגלאי חד-פעמי טעות אחת שורפת את הבדיקה כולה.
    'הוראות שימוש בגלאי:',
    '1. על מנת שלא לפגוע בצפיפות הגומות בגלאי, ושיבוש תוצאות הבדיקה, יש לשמור על הגלאי סגור הרמטית בתוך שקית המגן עד לתחילת הבדיקה, אין לחשוף אותו לאוויר לפני הבדיקה.',
    '',
    '2. אין להשתמש בגלאי אשר נשמר ללא חשיפה יותר מ-6 חודשים.',
    '',
    '3. הגלאי הינו לשימוש חד פעמי. לא ניתן להשתמש בו יותר מבדיקה אחת!',
    '',
    `תקופת הבדיקה היא ${days} ימים ומתחילה ביום ההתקנה.`,
    '',
    'חשוב: כדי שנוכל להתחיל לספור את התקופה ולעדכן אותך בסיומה,',
    'נא לכתוב לנו כאן בהודעה מתי התחלת את הבדיקה.',
    'אפשר פשוט לכתוב "התחלתי היום" או תאריך מדויק.',
    '',
    // רוב הלקוחות לא יעדכנו ביום ההצבה עצמו, ובלי המשפט הזה הם מניחים שהם
    // "פספסו את החלון" ופשוט לא כותבים כלום — וזה בדיוק המקרה שמשאיר אותנו
    // בלי תאריך התחלה. דיווח בדיעבד עדיף על אי-דיווח.
    'ואם שכחת לעדכן ביום ההצבה — לא נורא.',
    'פשוט כתוב לנו כאן את התאריך שבו התחלת, גם בדיעבד.',
  ];
  if (c.officePhone?.trim()) {
    lines.push('', `לשאלות: ${c.officePhone.trim()}`);
  }
  return lines.join('\n');
}

/**
 * הודעה 2 — נשלחת אוטומטית בתום תקופת הבדיקה.
 *
 * הלקוח קורא אותה 90 ימים אחרי השיחה האחרונה איתנו, ולכן היא חייבת להחזיר
 * את ההקשר בשורה אחת ולומר בדיוק מה לעשות. הנוסח זהה במתכוון לזה שבבוט
 * (`buildRadonKitReminderText`), כדי ששני הצדדים לא ייפרדו עם הזמן.
 */
export function buildKitReturnText(c: RadonKitMessageContext): string {
  const where = c.siteAddress?.trim() ? ` (${c.siteAddress.trim()})` : '';
  const lines = [
    c.customerName?.trim() ? `שלום ${c.customerName.trim()},` : 'שלום,',
    '',
    `כאן גלית — החברה לאיכות הסביבה. תקופת בדיקת הראדון${where} הסתיימה.`,
    '',
    'מה צריך לעשות עכשיו:',
    '1. להוריד את הגלאים מהמקומות שבהם הוצבו.',
    '2. להחזיר אותם לאריזה המקורית.',
    '3. לשלוח אלינו בחזרה בדואר, לפי ההוראות שצורפו לערכה.',
    '',
    'חשוב: בלי החזרת הגלאים אי אפשר לבצע את האנליזה במעבדה ולא ניתן להפיק דוח.',
    'ברגע שהגלאים יגיעו אלינו נעביר אותם לאנליזה ונשלח לך את הדוח.',
  ];
  if (c.officePhone?.trim()) {
    lines.push('', `לשאלות: ${c.officePhone.trim()}`);
  }
  return lines.join('\n');
}

